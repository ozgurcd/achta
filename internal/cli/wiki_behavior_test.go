func wikiBehaviorRun(t *testing.T, root string, want int, args ...string) string {
	t.Helper()
	var out, errout bytes.Buffer
	code := Run(append([]string{"--wiki-dir", filepath.Join(root, "wiki")}, args...), &out, &errout, buildinfo.Version)
	if code != want {
		t.Fatalf("%v: exit=%d want=%d output=%s stderr=%s", args, code, want, out.String(), errout.String())
	}
	return out.String()
}

func TestWikiBehaviorScope(t *testing.T) {
	root, _ := freshPinStaleDerive(t)
	writeTestFile(t, filepath.Join(root, "wiki/repos/broken.md"), "not valid frontmatter\n")
	out := wikiBehaviorRun(t, root, 0, "wiki", "check", "--only", "freshness", "--repo", "sample", "--json")
	if !strings.Contains(out, `"status":"not_judged"`) || !strings.Contains(out, "broken") || !strings.Contains(out, "not selected by --repo") {
		t.Fatalf("missing explicit exclusion: %s", out)
	}
	out = wikiBehaviorRun(t, root, 1, "wiki", "check", "--exclude", "broken=pin unchanged", "--json")
	if !strings.Contains(out, "pin unchanged") || !strings.Contains(out, `"name":"derive","status":"fail"`) {
		t.Fatalf("scope suppressed another judgement: %s", out)
	}
	out = wikiBehaviorRun(t, root, 0, "wiki", "check", "--exclude", "broken=pin unchanged", "--exclude", "sample=pin unchanged")
	if !strings.Contains(out, "NOT judged") || !strings.Contains(out, "sample") || !strings.Contains(out, "broken") {
		t.Fatalf("human exclusion missing: %s", out)
	}
	for _, args := range [][]string{{"--repo", "absent"}, {"--exclude", "sample"}, {"--exclude", "sample="}, {"--repo", "sample", "--exclude", "sample=conflict"}, {"--repo", "sample", "--repo", "sample"}} {
		wikiBehaviorRun(t, root, 2, append([]string{"wiki", "check", "--json"}, args...)...)
	}
	t.Log("PASS selected freshness; NOT judged broken with reason; derive still fails; malformed scopes exit 2")
}

func TestWikiBehaviorFreshnessEnforces(t *testing.T) {
	root, repo := freshPinStaleDerive(t)
	runGit(t, repo, "commit", "-am", "advance")
	out := wikiBehaviorRun(t, root, 1, "wiki", "freshness", "--repo", "sample", "--json")
	if !strings.Contains(out, `"mode":"enforcing"`) || !strings.Contains(out, `"status":"behind"`) {
		t.Fatalf("missing enforced drift: %s", out)
	}
	out = wikiBehaviorRun(t, root, 0, "wiki", "freshness", "--repo", "sample", "--report-only", "--json")
	if !strings.Contains(out, `"mode":"report_only"`) || !strings.Contains(out, `"status":"drift"`) {
		t.Fatalf("report mode hid drift: %s", out)
	}
	wikiBehaviorRun(t, root, 1, "wiki", "freshness", "--repo", "sample", "--strict")
	t.Log("PASS behind page: default exit 1; report_only exit 0 with drift retained")
}

func TestWikiBehaviorDerivePreviewAndHeader(t *testing.T) {
	root, _ := freshPinStaleDerive(t)
	page := filepath.Join(root, "wiki/repos/sample.md")
	before := readTestFile(t, page)
	for _, args := range [][]string{{"wiki", "derive", "--check", "--json"}, {"wiki", "derive", "--json"}} {
		out := wikiBehaviorRun(t, root, 1, args...)
		if readTestFile(t, page) != before {
			t.Fatal("read-only derive changed bytes")
		}
		if !strings.Contains(out, `"before":`) || !strings.Contains(out, `"after":`) || !strings.Contains(out, "Generated by achta "+buildinfo.Version) || strings.Contains(out, "wiki/tools/wiki-derive.sh") {
			t.Fatalf("missing honest preview/header: %s", out)
		}
	}
	out := wikiBehaviorRun(t, root, 0, "wiki", "derive", "--write", "--json")
	if !strings.Contains(out, `"status":"updated"`) || !strings.Contains(out, "wiki/repos/sample.md") {
		t.Fatalf("write not named: %s", out)
	}
	if readTestFile(t, page) == before {
		t.Fatal("explicit derive did not write")
	}
	wikiBehaviorRun(t, root, 0, "wiki", "derive", "--check")
	t.Log("PASS preview changes no byte; header names Achta version; --write names updated page")
}

func TestWikiBehaviorPinOnlyMetadata(t *testing.T) {
	root, _, head := testWorkspaceRepo(t, "sample")
	page := filepath.Join(root, "wiki/repos/sample.md")
	original := strings.ReplaceAll(pageFixtureCLI, "REPOSITORY", "sample")
	original = strings.Replace(original, "# sample\n", "# sample\n\nLead at aaaaaaa on 2026-09-01: old slice.\n", 1)
	for _, newline := range []string{"\n", "\r\n"} {
		before := strings.ReplaceAll(original, "\n", newline)
		writeTestFile(t, page, before)
		out := wikiBehaviorRun(t, root, 0, "wiki", "pin", "sample", "--sha", head, "--verified", "2026-09-17", "--attest-reviewed", "--json")
		want := strings.Replace(before, "verified_against: sample @ aaaaaaa", "verified_against: sample @ "+head, 1)
		want = strings.Replace(want, "verified: 2026-09-01", "verified: 2026-09-17", 1)
		want = strings.Replace(want, "updated: 2026-09-01", "updated: 2026-09-17", 1)
		if got := readTestFile(t, page); got != want {
			t.Fatalf("pin changed more or less than pin/dates:\n%s", got)
		}
		if !strings.Contains(out, "PM") || !strings.Contains(out, "front lead") {
			t.Fatalf("missing ownership notice: %s", out)
		}
	}
	t.Log("PASS pin and both dates advance; DERIVED and lead bytes identical (LF and CRLF)")
}

