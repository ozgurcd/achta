func TestWikiBehaviorExplicitWikiWrites(t *testing.T) {
	selected, _, head := testWorkspaceRepo(t, "sample")
	other, _, _ := testWorkspaceRepo(t, "sample")
	page := strings.ReplaceAll(pageFixtureCLI, "REPOSITORY", "sample")
	for _, root := range []string{selected, other} {
		writeTestFile(t, filepath.Join(root, "wiki/repos/sample.md"), page)
	}
	t.Chdir(other)
	wikiBehaviorRun(t, selected, 0, "wiki", "pin", "sample", "--sha", head, "--verified", "2026-09-17", "--attest-reviewed")
	// Use the existing --check API before any changes to prove selected reads too.
	wikiBehaviorRun(t, selected, 1, "wiki", "derive", "--check")
	wikiBehaviorRun(t, selected, 0, "wiki", "derive", "--write")
	if readTestFile(t, filepath.Join(other, "wiki/repos/sample.md")) != page {
		t.Fatal("pin or preview wrote to ambient wiki")
	}
	if !strings.Contains(readTestFile(t, filepath.Join(selected, "wiki/repos/sample.md")), head) {
		t.Fatal("selected wiki was not pinned")
	}
	register := "# Decisions\n\n## Platform\n\n### P-001 — first choice\nExisting body.\n\n## UI\n"
	for _, root := range []string{selected, other} {
		writeTestFile(t, filepath.Join(root, "wiki/platform/decisions.md"), register)
	}
	writeTestFile(t, filepath.Join(selected, "body.txt"), "Measured choice.\n")
	wikiBehaviorRun(t, selected, 0, "decision", "add", "--title", "Selection", "--body-file", "body.txt")
	if readTestFile(t, filepath.Join(other, "wiki/platform/decisions.md")) != register {
		t.Fatal("decision wrote to ambient wiki")
	}
	if !strings.Contains(readTestFile(t, filepath.Join(selected, "wiki/platform/decisions.md")), "P-002 — Selection") {
		t.Fatal("decision ignored selected wiki")
	}
	t.Log("PASS --wiki-dir pin and decision writes and derive reads select the requested wiki from another workspace")
}

func TestWikiBehaviorFailureAndHelp(t *testing.T) {
	root, _ := freshPinStaleDerive(t)
	writeTestFile(t, filepath.Join(root, "wiki/repos/broken.md"), "broken\n")
	out := wikiBehaviorRun(t, root, 2, "wiki", "freshness", "--report-only", "--json")
	if !strings.Contains(out, `"mode":"report_only"`) || !strings.Contains(out, `"status":"cannot_evaluate"`) {
		t.Fatalf("report hid unavailable evidence: %s", out)
	}
	// Unknown global flags cannot be used to change the authoritative workspace.
	wikiBehaviorRun(t, root, 2, "wiki", "derive", "--write", "--check", "--json")
	wikiBehaviorRun(t, root, 2, "wiki", "freshness", "--strict=false", "--json")
	// A selected failure must not erase the scope report.
	out = wikiBehaviorRun(t, root, 2, "wiki", "check", "--exclude", "sample=pin unchanged", "--json")
	if !strings.Contains(out, `"not_judged":{"sample":"pin unchanged"}`) {
		t.Fatalf("failure hid exclusions: %s", out)
	}
	for _, pair := range []struct{ family, command, flag string }{{"wiki", "check", "--exclude"}, {"wiki", "freshness", "--report-only"}, {"wiki", "derive", "--write"}, {"wiki", "pin", "front lead"}, {"recipe", "check", "--expect-order"}} {
		var stdout, stderr bytes.Buffer
		if code := Run([]string{pair.family, pair.command, "--help"}, &stdout, &stderr, buildinfo.Version); code != 0 || !strings.Contains(stdout.String(), pair.flag) {
			t.Fatalf("help %s %s: code=%d %s %s", pair.family, pair.command, code, stdout.String(), stderr.String())
		}
	}
}

func TestWikiBehaviorPreviewBytesAndRecipeMultiplicity(t *testing.T) {
	root, _ := freshPinStaleDerive(t)
	page := filepath.Join(root, "wiki/repos/sample.md")
	before := readTestFile(t, page)
	var doc struct {
		Pages []struct{ Before, After string }
	}
	out := wikiBehaviorRun(t, root, 1, "wiki", "derive", "--check", "--json")
	if err := json.Unmarshal([]byte(out), &doc); err != nil || len(doc.Pages) != 1 {
		t.Fatalf("bad preview: %v %s", err, out)
	}
	if doc.Pages[0].Before != before {
		t.Fatal("preview before does not match actual bytes")
	}
	wikiBehaviorRun(t, root, 0, "wiki", "derive", "--write")
	if doc.Pages[0].After != readTestFile(t, page) {
		t.Fatal("preview after does not match written bytes")
	}
	writeTestFile(t, filepath.Join(root, "Makefile"), "check:\n\tfirst\n")
	wikiBehaviorRun(t, root, 1, "recipe", "check", "--makefile", "Makefile", "--target", "check", "--expect-line", "first", "--expect-line", "first", "--expect-order")
	wikiBehaviorRun(t, root, 2, "recipe", "check", "--makefile", "Makefile", "--target", "check", "--expect-order")
}
